import gzip, json, csv, io, sys
R = sys.argv[1]  # path to officials-network-graph/public/data
OUT = sys.argv[2] if len(sys.argv) > 2 else 'data/aklan.js'
YEARS = [2001,2004,2007,2010,2013,2016,2019,2022,2025]
rows = []
for y in YEARS:
    for r in csv.DictReader(io.TextIOWrapper(gzip.open(f'{R}/winners/{y}.csv.gz'), encoding='utf-8')):
        if r['province'] != 'AKLAN': continue
        rows.append([y, r['city'], r['district'], r['position'], r['last_name'], r['first_name'], r['middle_name'],
                     r['title'], r['party'], int(r['votes']) if r['votes'] else 0, r['person_id']])
prov = json.load(gzip.open(f'{R}/prov/aklan.json.gz'))
ids = {r[10] for r in rows if r[10]}
rec = {}
for c in prov['contests']:
    n = len(c['c'])
    for (pid, party, votes, won, rank, *_ ) in c['c']:
        if pid not in ids: continue
        share = round(votes / c['total'] * 100, 1) if c['seats'] == 1 and c['total'] and votes else None
        rec.setdefault(pid, []).append([c['year'], c['position'], c['city'], c['district'], party, votes, share, rank, n, won, c['seats'], c['uncontested']])
people = {pid: prov['persons'][pid][:4] for pid in ids if pid in prov['persons']}
geo = json.load(gzip.open(f'{R}/geo/cities/aklan.json.gz'))
def rnd(c): return [rnd(x) for x in c] if isinstance(c[0], list) else [round(c[0],4), round(c[1],4)]
def signed(r): return sum((r[i+1][0]-r[i][0])*(r[i+1][1]+r[i][1]) for i in range(len(r)-1))
def rewind(poly):
    # d3-geo needs clockwise exterior rings; RFC 7946 GeoJSON is counter-clockwise.
    # Wrong winding makes d3 draw the whole globe minus the town (a big filled box).
    return [ring if (signed(ring) > 0) == (i == 0) else ring[::-1] for i, ring in enumerate(poly)]
for f in geo['features']:
    g = f['geometry']
    c = rnd(g['coordinates'])
    g['coordinates'] = rewind(c) if g['type'] == 'Polygon' else [rewind(p) for p in c]
    f['properties'] = {'name': f['properties']['name'], 'label': f['properties']['label']}
out = {'years': YEARS, 'poverty': prov['poverty'], 'rows': rows, 'rec': rec, 'people': people, 'geo': geo}
s = json.dumps(out, separators=(',', ':'), ensure_ascii=False)
open(OUT, 'w').write('// Generated by scripts/build_data.py. Do not edit by hand.\nwindow.AKLAN_DATA = ' + s + ';\n')
print(len(rows), 'winner rows;', len(rec), 'records;', len(s)//1024, 'KB')
print(sorted({f['properties']['name'] for f in geo['features']}))
print(sorted({r[1] for r in rows}))
